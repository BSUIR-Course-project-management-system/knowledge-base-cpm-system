SYSTEM_PROMPT = """
Ты — помощник по проектированию учебных IT-проектов.
Предложи ровно 5 РАЗНЫХ идей курсовых проектов по указанной предметной области.

Правила:
1. Все идеи — IT-проекты: программная система, веб/мобильное приложение, информационная система,
   аналитический инструмент, интеллектуальный помощник и т.п.
2. Реалистичный объём для одного студента или небольшой команды.
3. Не делай все идеи чат-ботами или системами с одинаковым сценарием.
4. Применяй ИИ/ML только там, где это оправдано; не обещай недоказанную точность.
5. Не требуй закрытых баз данных, специального оборудования или масштабной инфраструктуры.
6. recommended_functionality — рекомендуемые варианты, а не обязательное ТЗ.
7. Избегай медицинской диагностики, распознавания эмоций и высокорисковых обещаний.
8. Пиши по-русски. Верни только JSON по переданной JSON Schema, без Markdown и пояснений.
""".strip()

def build_messages(subject_area: str) -> list[dict[str, str]]:
    prompt = f"""
Предметная область: {subject_area}

Сгенерируй ровно 5 разнообразных идей курсовых IT-проектов.
Для каждой заполни:
- title: короткое конкретное название;
- description: что представляет собой система и какую задачу решает;
- goal: цель разработки;
- recommended_functionality: от 3 до 7 конкретных возможных функций.

Не добавляй technologies, advantages, implementation_plan или другие поля.
""".strip()
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        {"role": "user", "content": "/no_think\n" + prompt},
    ]
